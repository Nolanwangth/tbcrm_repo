const product = (id: string, city: string, category: PriceProduct["category"], nameZh: string, nameEn: string, costPrice: number, quotePrice: number, unit: PriceProduct["unit"], extra: Partial<PriceProduct> = {}): PriceProduct => ({
    id,
    city,
    category,
    nameZh,
    nameEn,
    costPrice,
    quotePrice,
    unit,
    enabled: true,
    demo: true,
    ...extra,
});
const vehicleProducts = (cityCode: string, city: string): PriceProduct[] => {
    const categories: Array<[
        PriceProduct["category"],
        string,
        string,
        number
    ]> = [
        ["市区用车", "市区用车", "City car service", 0],
        ["郊区用车", "郊区用车", "Outskirts car service", 160],
        ["接机", "接机服务", "Airport pickup", -80],
        ["送机", "送机服务", "Airport transfer", -80],
    ];
    const seats: Array<[
        number,
        number,
        number
    ]> = [
        [5, 300, 440],
        [7, 400, 560],
        [9, 520, 720],
    ];
    return categories.flatMap(([category, zh, en, delta], categoryIndex) => seats.map(([seatCount, costPrice, quotePrice]) => product(`${cityCode}-vehicle-${categoryIndex}-${seatCount}`, city, category, `${seatCount}座${zh}（${city}）`, `${seatCount}-seat ${en}`, Math.max(180, costPrice + delta), Math.max(300, quotePrice + delta), "每天", { seatCount })));
};
