begin;
set local role service_role;
do $$
declare actor uuid; customer uuid; other_customer uuid; proposal uuid:=gen_random_uuid(); request uuid:=gen_random_uuid(); snapshot jsonb; draft jsonb; published jsonb; repeated jsonb; group_row jsonb; denied boolean; file uuid; version uuid;
begin
 select id into actor from crm_users where role='admin' and active and not must_change_password limit 1;
 select id into customer from customers where status='跟进中' limit 1;
 select id into other_customer from customers where id<>customer limit 1;
 group_row:=crm_save_quote_v2_group(actor,customer,'[事务测试] 独立分组',null);
 snapshot:=jsonb_build_object('schemaVersion',2,'sourceVersion','2.0.0','customerId',customer,'toolType','quotation','title','[事务测试] 2.0 报价','travelerCount',3,'groupId',group_row->>'id','settings',jsonb_build_object('currency','RMB'),'directQuote',jsonb_build_object('items',jsonb_build_array(jsonb_build_object('libraryQuote',jsonb_build_object('specification','儿童票'),'serviceHours',8,'quantity',2,'quotePrice',200))));
 draft:=crm_save_quote_v2(actor,customer,proposal,0,snapshot,null,null);
 if (draft->>'revision')::integer<>1 then raise exception 'Draft revision incorrect';end if;
 if (select editor_snapshot from customer_proposals where id=proposal)<>snapshot then raise exception 'Snapshot lost 2.0 fields';end if;
 denied:=false;
 begin perform crm_save_quote_v2(actor,customer,proposal,0,snapshot,null,null);exception when others then denied:=sqlerrm like 'CONFLICT:%';end;
 if not denied then raise exception 'Stale draft overwritten';end if;
 published:=crm_save_quote_v2(actor,customer,proposal,1,snapshot,request,'初稿');
 repeated:=crm_save_quote_v2(actor,customer,proposal,1,snapshot,request,'初稿');
 if published->>'versionId'<>repeated->>'versionId' or (select count(*) from customer_proposal_versions where proposal_id=proposal)<>1 then raise exception 'Duplicate publish';end if;
 denied:=false;
 begin perform crm_save_quote_v2(actor,customer,proposal,2,snapshot,null,null);exception when others then denied:=sqlerrm like '正式版本只读%';end;
 if not denied then raise exception 'Published version editable';end if;
 version:=(published->>'versionId')::uuid;
 denied:=false;
 begin update customer_proposal_versions set snapshot='{}' where id=version;exception when others then denied:=true;end;
 if not denied then raise exception 'Immutable snapshot trigger missing';end if;
 file:=crm_register_proposal_pdf(actor,version,customer::text||'/proposals/'||version::text||'.pdf',100,repeat('a',64));
 if file<>crm_register_proposal_pdf(actor,version,customer::text||'/proposals/'||version::text||'.pdf',100,repeat('a',64)) then raise exception 'PDF duplicated';end if;
 if (select count(*) from customer_proposal_documents where proposal_version_id=version)<>1 then raise exception 'PDF document link missing';end if;
 denied:=false;
 begin perform crm_save_quote_v2(actor,other_customer,gen_random_uuid(),0,snapshot,null,null);exception when others then denied:=true;end;
 if not denied then raise exception 'Cross-customer snapshot accepted';end if;
 update customers set status='已关闭',closed_at=now(),close_reason='测试关闭' where id=customer;
 denied:=false;
 begin perform crm_save_quote_v2(actor,customer,gen_random_uuid(),0,snapshot,null,null);exception when others then denied:=true;end;
 if not denied then raise exception 'Closed customer writable';end if;
 if not exists(select 1 from crm_quote_v2_events where actor_user_id=actor and customer_id=customer and action='group_saved') then raise exception 'Group audit missing';end if;
 if has_table_privilege('anon','crm_quote_v2_groups','SELECT') or has_function_privilege('authenticated','crm_save_quote_v2(uuid,uuid,uuid,integer,jsonb,uuid,text)','EXECUTE') then raise exception 'Direct client access open';end if;
 raise notice 'PASS: 2.0 full snapshot, customer/group links, draft conflict, idempotent publish, immutable version/PDF link, closed-customer policy, group audit and access restrictions';
end $$;
rollback;
