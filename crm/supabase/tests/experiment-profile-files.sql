begin;
set local role service_role;
do $$
declare actor uuid; customer uuid; other_customer uuid; original_stamp timestamptz; current_stamp timestamptz; file_a uuid; file_b uuid; link_a uuid; denied boolean; customer_input jsonb; travel_input jsonb; score_input jsonb; created jsonb; count_before bigint;
begin
 select id into actor from crm_users where role='admin' and active and not must_change_password limit 1;
 select id,updated_at into customer,original_stamp from customers where status='跟进中' limit 1;
 select id into other_customer from customers where id<>customer limit 1;
 select to_jsonb(c)-'id'-'created_at'-'updated_at' into customer_input from customers c where id=customer;
 select to_jsonb(t)-'id'-'customer_id'-'created_at'-'updated_at' into travel_input from travel_needs t where customer_id=customer;
 select to_jsonb(s)-'id'-'customer_id'-'created_at'-'updated_at' into score_input from initial_scores s where customer_id=customer;
 created:=crm_create_customer_bundle(actor,customer_input||'{"name":"[事务测试] 原子创建"}',travel_input,score_input);
 if not exists(select 1 from audit_logs where customer_id=(created->>'id')::uuid and actor_user_id=actor and field_name='客户创建') then raise exception 'Customer creation audit missing';end if;
 if not exists(select 1 from score_versions where customer_id=(created->>'id')::uuid) then raise exception 'Customer creation score missing';end if;
 select count(*) into count_before from customers;
 denied:=false;
 begin perform crm_create_customer_bundle(actor,customer_input,travel_input||'{"not_a_column":"invalid"}',score_input);exception when others then denied:=true;end;
 if not denied or (select count(*) from customers)<>count_before then raise exception 'Partial customer creation survived failed companion write';end if;
 perform crm_update_customer_control(actor,customer,'priority','低',customer_input->>'priority');
 if not exists(select 1 from audit_logs where customer_id=customer and field_name='优先级' and new_value='低' and actor_user_id=actor) and customer_input->>'priority'<>'低' then raise exception 'Control audit missing';end if;
 select updated_at into original_stamp from customers where id=customer;
 perform crm_update_customer_profile(actor,customer,original_stamp,'{"name":"[事务测试] 客户编辑"}','{"special_requirements":"[事务测试] 饮食要求"}');
 select updated_at into current_stamp from customers where id=customer;
 if current_stamp=original_stamp then raise exception 'Customer revision not advanced';end if;
 if not exists(select 1 from audit_logs where customer_id=customer and field_name='name' and new_value='[事务测试] 客户编辑' and actor_user_id=actor) then raise exception 'Atomic customer audit missing';end if;
 denied:=false;
 begin perform crm_update_customer_profile(actor,customer,original_stamp,'{"name":"错误覆盖"}','{}');exception when others then denied:=sqlerrm like 'CONFLICT:%';end;
 if not denied then raise exception 'Stale customer input accepted';end if;
 denied:=false;
 begin perform crm_update_customer_profile(actor,customer,current_stamp,'{"status":"已关闭"}','{}');exception when others then denied:=true;end;
 if not denied then raise exception 'Profile field whitelist bypassed';end if;
 insert into customer_files(customer_id,name,storage_path,size_bytes,mime_type) values(customer,'contract.pdf','test/contract.pdf',100,'application/pdf') returning id into file_a;
 insert into customer_files(customer_id,name,storage_path,size_bytes,mime_type) values(other_customer,'wrong.pdf','test/wrong.pdf',100,'application/pdf') returning id into file_b;
 perform crm_link_customer_document(actor,customer,file_a,'contract',null);
 select id into link_a from customer_document_links where customer_id=customer and document_type='contract' and replaced_at is null;
 if link_a is null then raise exception 'Contract link missing';end if;
 denied:=false;
 begin perform crm_link_customer_document(actor,customer,file_b,'contract',link_a);exception when others then denied:=true;end;
 if not denied then raise exception 'Cross-customer attachment accepted';end if;
 denied:=false;
 begin perform crm_link_customer_document(actor,customer,file_a,'contract',null);exception when others then denied:=sqlerrm like 'CONFLICT:%';end;
 if not denied then raise exception 'Concurrent file replacement accepted';end if;
 if has_function_privilege('authenticated','crm_update_customer_profile(uuid,uuid,timestamptz,jsonb,jsonb)','EXECUTE') then raise exception 'Direct profile privilege open';end if;
 raise notice 'PASS: transactional profile audit, optimistic conflict, field whitelist, attachment association and concurrent replacement';
end $$;
rollback;
